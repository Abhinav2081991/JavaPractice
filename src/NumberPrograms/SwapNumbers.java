package NumberPrograms;

public class SwapNumbers {

    public static void main(String[] args) {

        int a = 10;
        int b = 12;

        System.out.println(a);
        System.out.println(b);

        a = a+b;    //22
        b = a-b;  //22-12 =10

        a = a-b; //22-10 = 12

        System.out.println(a);
        System.out.println(b);



    }
}
