public class SwitchPractice {

    public static void main(String[] args) {


        int i =10;

        switch (i){
            case  1:
                System.out.println("Output is "  + i);
                break;
            case  10:
                System.out.println("Output is "  + i);
                break;
            default:
                System.out.println("Default");
        }
    }
}
